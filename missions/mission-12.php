    <main class="cv mission-page">
        <section class="cv-card">
            <h2>Contexte</h2>
            <p>Lors d'une intervention sur site, j'ai participé à la réorganisation de baies informatiques et au rebrassage des connexions réseau. Le travail concernait les switchs, les panneaux de brassage RJ45 et les bornes Wi-Fi.</p>
        </section>

        <section class="cv-card">
            <h2>Objectifs</h2>
            <p>Rendre le câblage plus lisible et faciliter les prochaines interventions en identifiant clairement les équipements, les ports et les liaisons.</p>
        </section>

        <section class="cv-card">
            <h2>Tâches réalisées</h2>
            <ul>
                <li>Repérage des switchs et des ports utilisés avant de débrancher les cordons.</li>
                <li>Débrassage puis rebrassage des liaisons RJ45 en suivant le repérage des ports.</li>
                <li>Réorganisation des baies informatiques et rangement des cordons de brassage.</li>
                <li>Étiquetage des liaisons pour faciliter leur identification.</li>
                <li>Intervention sur les bornes Wi-Fi présentes sur le site.</li>
            </ul>
        </section>

        <section class="cv-card">
            <h2>Compétences développées</h2>
            <ul>
                <li>Identifier les composants d'une infrastructure réseau physique et le rôle des ports de brassage.</li>
                <li>Intervenir sur le câblage d'une baie en s'appuyant sur un repérage préalable.</li>
                <li>Documenter les liaisons par un étiquetage utile à la maintenance.</li>
            </ul>
        </section>

        <section class="cv-card">
            <h2>Bilan personnel</h2>
            <p>Cette intervention m'a montré l'intérêt de repérer les ports avant de débrancher un cordon. Un câblage bien rangé et étiqueté ne sert pas seulement à rendre la baie plus propre : il aide à retrouver une liaison lors d'une panne ou d'une modification.</p>
        </section>

        <section class="cv-card">
            <h2>Réponse au besoin et justification</h2>
            <p>Le repérage préalable des ports permet de conserver la correspondance des liaisons pendant le débrassage. Le rebrassage et le regroupement des cordons rendent la baie plus lisible ; l’étiquetage facilite ensuite l’identification des connexions. Les équipements concernés sont les switchs, panneaux RJ45 et bornes Wi-Fi du site client.</p>
        </section>

        <section class="cv-card">
            <h2>Tests et résultat obtenu</h2>
            <p>Les photos montrent le câblage avant intervention et sa réorganisation. Elles constituent une preuve visuelle du rangement.</p><p>Je n’ai pas effectué de test de connectivité après le rebrassage. Je ne peux donc pas attester personnellement du fonctionnement des postes ou du Wi-Fi à partir de cette intervention. Ces contrôles restent nécessaires pour valider le fonctionnement du réseau.</p><p>Le site exact, la date et la nature précise de l’intervention Wi-Fi restent à renseigner.</p>
        </section>

        <section class="cv-card">
            <h2>Compétences mobilisées</h2>
            <ul><li>Gérer le patrimoine informatique : repérer les équipements, les ports et les liaisons.</li><li>Répondre aux incidents et aux demandes d’assistance et d’évolution : intervenir sur une demande de réorganisation.</li><li>Mettre à disposition un service informatique : préparer la vérification des liaisons après intervention.</li></ul>
        </section>

        <section class="cv-card">
            <h2>Déroulement de l’intervention</h2>
            <p>J’ai commencé par repérer les switchs, leurs ports et les liaisons RJ45 concernées. Ce repérage permet de savoir quelle connexion est déplacée et d’éviter de rebrancher au hasard pendant le réaménagement.</p>
            <p>Le travail a ensuite consisté à débrasser et rebrasser les cordons en suivant les correspondances repérées. J’ai participé à la réorganisation des baies et au regroupement des câbles pour rendre leur cheminement plus lisible.</p>
            <p>L’étiquetage fait partie de l’intervention : il permet de retrouver les liaisons lors d’une opération ultérieure. Les photos avant et après montrent la différence d’organisation, mais ne constituent pas un relevé de tests électriques ou réseau.</p>
            <p>L’intervention concernait aussi les bornes Wi-Fi. La nature précise de cette partie reste à documenter : je ne prétends pas avoir configuré des SSID, VLAN, contrôleurs ou paramètres radio sans information correspondante.</p>
            <p>Je n’ai pas réalisé les contrôles de connectivité après le rebrassage. Le résultat que je peux présenter est donc la réorganisation physique et son repérage, sans affirmer que j’ai validé le fonctionnement de chaque poste ou du Wi-Fi.</p>
        </section>

